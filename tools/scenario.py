"""Run a controlled synthetic scenario against your own VesselOps instance."""

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import urllib.error
import urllib.parse
import urllib.request
import uuid


def execute(base_url, token):
    parsed = urllib.parse.urlparse(base_url)
    if (
        parsed.scheme not in ("http", "https")
        or not parsed.netloc
        or parsed.username
        or parsed.password
        or parsed.query
        or parsed.fragment
    ):
        raise ValueError("use a base URL without credentials, query or fragment")
    if parsed.scheme == "http" and parsed.hostname not in ("127.0.0.1", "localhost", "::1"):
        raise ValueError("HTTP is permitted only for localhost; use HTTPS remotely")
    if len(token) < 32:
        raise ValueError("set API_TOKEN in your environment")

    class NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *args):
            return None  # Do not forward the operator token to redirected endpoints.

    opener = urllib.request.build_opener(NoRedirect())

    def call(path, method="GET", body=None, credential=None):
        req = urllib.request.Request(
            base_url.rstrip("/") + path,
            method=method,
            data=json.dumps(body).encode() if body is not None else None,
            headers={
                "Authorization": "Bearer " + (credential if credential is not None else token),
                "Content-Type": "application/json",
            },
        )
        try:
            with opener.open(req, timeout=30) as response:
                return response.status, json.load(response), response.headers.get("X-Request-ID")
        except urllib.error.HTTPError as response:
            return response.code, json.load(response), response.headers.get("X-Request-ID")

    code, ready, _ = call("/health/ready")
    if code != 200:
        raise RuntimeError(f"Readiness failed with HTTP {code}: {ready.get('error', 'unknown')}")
    failures = []
    for _ in range(5):
        code, _, request_id = call("/api/state", credential="controlled-invalid-lab-token")
        if code != 401:
            raise RuntimeError("Expected rejected authentication")
        failures.append(request_id)
    tag = "LAB-" + uuid.uuid4().hex[:6].upper()
    code, _, _ = call(
        "/api/assets", "POST", {"tag": tag, "hostname": "synthetic-workstation", "owner": "Demo operator"}
    )
    if code != 201:
        raise RuntimeError("Asset creation failed")
    code, ticket, _ = call(
        "/api/tickets",
        "POST",
        {
            "title": "Investigate controlled rejected operator requests",
            "priority": "P2",
            "category": "security",
            "asset_id": tag,
        },
    )
    if code != 201:
        raise RuntimeError("Ticket creation failed")
    for status, note in [
        (
            "in_progress",
            "Controlled lab: correlated five rejected requests by request ID; checking expected operator activity.",
        ),
        (
            "resolved",
            "Confirmed these five requests were generated by the authorized scenario tool. No evidence of external compromise. Verified a valid operator session still works.",
        ),
    ]:
        code, ticket, _ = call(
            "/api/tickets/" + ticket["id"], "PATCH", {"status": status, "note": note, "version": ticket["version"]}
        )
        if code != 200:
            raise RuntimeError("Ticket update failed")
    code, incident, _ = call(
        "/api/incidents",
        "POST",
        {
            "title": "Controlled authentication failure exercise",
            "severity": "medium",
            "source": "synthetic",
            "event_ids": failures,
            "summary": "Five intentionally invalid operator requests were rejected. Request IDs are attached for correlation with exported console logs. Related ticket: "
            + ticket["id"],
        },
    )
    if code != 201:
        raise RuntimeError("Incident creation failed")
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "provenance": "controlled synthetic scenario against caller-selected own instance",
        "storage": ready["storage"],
        "expected_rejections": len(failures),
        "request_ids": failures,
        "ticket_id": ticket["id"],
        "ticket_status": ticket["status"],
        "incident_id": incident["id"],
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default="http://127.0.0.1:8080")
    parser.add_argument("--output", type=Path, default=Path("evidence/my_scenario.json"))
    args = parser.parse_args()
    result = execute(args.base_url, os.environ.get("API_TOKEN", ""))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))
